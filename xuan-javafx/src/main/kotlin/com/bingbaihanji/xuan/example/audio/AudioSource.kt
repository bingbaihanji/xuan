package com.bingbaihanji.xuan.example.audio

/**
 * 一个音频源：文件（拉到尾就停）或麦克风（一直有）。
 *
 * 规格见 `docs/superpowers/specs/2026-10-09-audio-fft-demo-design.md` §5。
 *
 * 三个视图（时域波形 / 频谱折线 / 声谱图）共用同一个下游环形缓冲，所以**采集是单写者**：
 * [drainInto] 只在 GL 线程（渲染回调）里被调用，线程安全由实现自己保证。
 *
 * 换源的两条约定**都由调用方负责**，实现管不了：
 * 1. 先 `stop()` 旧源再 `start()` 新源。两个采集线程同时往一个下游缓冲里灌，
 *    下游看到的是两段互不相干的信号拼在一起。
 * 2. **下游那个环形缓冲必须重建**。它的写指针单调递增，而换源意味着新数据与旧数据没有关系；
 *    沿用旧缓冲会让 `SeriesBuffer` 那条"写入总数倒退就抛异常"的契约被触发。
 */
interface AudioSource {
    /** 采样率（Hz）。源切了它就没意义了——下游要按它重建。 */
    val sampleRate: Int

    /** 开始产生样本（文件＝从头读，麦克风＝开始采）。重复调用＝重新开始。 */
    fun start()

    /** 停止采集。停止后可以再 [start]。 */
    fun stop()

    /**
     * 把"自上次调用以来新增的样本"追加进 [sink]，只在 GL 线程（渲染回调）里调用。
     *
     * [sink] 的两个参数是"数组 + 有效长度"，**只读 `[0, len)`**。
     * 注意：那个数组由实现复用、或来自实现内部的队列，**回调返回后即视为失效**——
     * 要留着就必须自己拷一份。接口签名的形状给不出这条约束，所以写在这里。
     *
     * 一次调用**可以**触发多次 [sink]（队列里积压了好几块时就是这样），按顺序追加即可。
     */
    fun drainInto(sink: (FloatArray, Int) -> Unit)
}
